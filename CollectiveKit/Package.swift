// swift-tools-version: 6.0
import PackageDescription

let package = Package(
    name: "CollectiveKit",
    defaultLocalization: "en",
    platforms: [.macOS(.v15)],
    products: [
        .library(name: "CollectiveKit", targets: ["CollectiveKit"]),
        .library(name: "CollectiveUI", targets: ["CollectiveUI"]),
        // Measures the cold spool backlog; not part of the app.
        .executable(name: "collective-bench", targets: ["CollectiveBench"]),
        // Writes the Sparkle appcast for scripts/release.sh; not part of the app.
        .executable(name: "collective-appcast", targets: ["CollectiveAppcast"]),
    ],
    dependencies: [
        .package(path: "../SubspaceKit"),
        .package(url: "https://github.com/swiftlang/swift-markdown", .upToNextMinor(from: "0.9.0")),
        // The parser swift-markdown builds on, asked for exactly as swift-markdown
        // asks for it: one copy is resolved for both, so they cannot differ.
        .package(url: "https://github.com/swiftlang/swift-cmark.git", from: "0.9.0"),
        // Reads the tinted-theming YAML schemes the themes are derived from.
        .package(url: "https://github.com/jpsim/Yams.git", from: "6.2.0"),
    ],
    targets: [
        .target(
            name: "CollectiveKit",
            dependencies: [
                .product(name: "SubspaceKit", package: "SubspaceKit"),
                // Parses agent replies for the popover's plain-text preview and
                // into the blocks the reply views lay out.
                .product(name: "Markdown", package: "swift-markdown"),
                // Measures how deep a reply nests before swift-markdown gets it.
                .product(name: "cmark-gfm", package: "swift-cmark"),
                .product(name: "cmark-gfm-extensions", package: "swift-cmark"),
                // Reads the base16 and base24 color schemes.
                .product(name: "Yams", package: "Yams"),
            ],
            resources: [
                .process("Resources/Localizable.xcstrings"),
                // The tools' logos the adapters name; their license is in Acknowledgements.json.
                .process("Resources/SourceIcons.xcassets"),
                .copy("Resources/Schemes"),
                // Generated by scripts/acknowledgements.sh; AcknowledgementsTests keeps it in step.
                .copy("Resources/Acknowledgements.json"),
                // A copy of the repo's ReleaseNotes.md; scripts/release.sh and ReleaseNotesTests keep it in step.
                .copy("Resources/ReleaseNotes.md"),
            ]
        ),
        // SwiftUI building blocks of the popover. A separate target keeps
        // CollectiveKit free of UI; the views only render `PopoverModel` values.
        .target(
            name: "CollectiveUI",
            dependencies: [
                "CollectiveKit",
                .product(name: "SubspaceKit", package: "SubspaceKit"),
            ],
            resources: [
                .process("Resources/Localizable.xcstrings"),
                // Copied as folders, so each license and NOTICE stays next to what it covers.
                .copy("Resources/Fonts"),
                .process("Resources/Lucide.xcassets"),
                .copy("Resources/Lucide"),
            ]
        ),
        .executableTarget(
            name: "CollectiveAppcast",
            dependencies: ["CollectiveKit"]
        ),
        .executableTarget(
            name: "CollectiveBench",
            dependencies: ["CollectiveKit", .product(name: "SubspaceKit", package: "SubspaceKit")]
        ),
        .testTarget(
            name: "CollectiveKitTests",
            dependencies: ["CollectiveKit", "CollectiveUI", .product(name: "SubspaceKit", package: "SubspaceKit")],
            resources: [.copy("Fixtures")]
        ),
    ]
)
